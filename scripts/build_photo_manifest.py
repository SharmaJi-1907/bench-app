#!/usr/bin/env python3
"""Generate js/photos.js listing which catalog items have a stock photo.

The app needs to know, without a network round-trip or a broken-image flash,
whether a given item id has a bundled photo. This walks
assets/processed_images/ and writes a plain global the other scripts can read.

Usage:
    python3 scripts/build_photo_manifest.py
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROCESSED = ROOT / "assets" / "processed_images"
DEST = ROOT / "js" / "photos.js"


def main():
    if not PROCESSED.is_dir():
        raise SystemExit(f"missing {PROCESSED}")

    ids = sorted(p.stem for p in PROCESSED.glob("*.jpg"))
    body = json.dumps(ids, separators=(",", ":"))
    DEST.write_text(
        "/* Generated by scripts/build_photo_manifest.py - do not edit by hand.\n"
        "   Catalog ids that ship with a bundled stock photo under\n"
        "   assets/processed_images/<id>.jpg */\n"
        f"const STOCK_PHOTOS=new Set({body});\n"
        "const stockPhoto=id=>STOCK_PHOTOS.has(id)?'assets/processed_images/'+id+'.jpg':null;\n"
    )
    print(f"wrote {DEST.relative_to(ROOT)} with {len(ids)} photo ids")


if __name__ == "__main__":
    main()
